"""
Run both attribution families for the 16-query bank.

Traj:
  target=reference
  target=next
  parameter source = TRACIN_PARAM_SOURCE (default raw)

DAS:
  projected dimension 4096
  later-JAX logic implementation
  parameter source = DAS_PARAM_SOURCE (default EMA)
  lambda sweep from DAS_LAMBDAS

This file intentionally launches one query at a time so jobs are resumable.
"""
import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

from exp_config import *


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gpu", type=int, default=0)
    ap.add_argument("--method", choices=["traj_ref", "traj_next", "das", "all"], default="all")
    args = ap.parse_args()

    with open(QUERY_DIR / "manifest.json") as f:
        qs = json.load(f)

    # These runner files are generated by this experiment package.
    # They consume one query record and save scores over all 5000 train points.
    wanted = (
        ["traj_ref", "traj_next", "das"]
        if args.method == "all"
        else [args.method]
    )

    for q in qs:
        qjson = Path(q["dir"]) / "query.json"
        for method in wanted:
            out = ATTR_DIR / method / f"q{q['query_id']:02d}"
            if (out / "scores.npy").exists() or any(out.glob("lambda_*/scores.npy")):
                print(f"[skip] {method} q{q['query_id']:02d}")
                continue
            runner = "attribution_one_query.py"
            cmd = [
                sys.executable, runner,
                "--query-json", str(qjson),
                "--method", method,
                "--gpu", str(args.gpu),
            ]
            print("$", " ".join(cmd), flush=True)
            rc = subprocess.call(cmd)
            if rc != 0:
                raise SystemExit(rc)


if __name__ == "__main__":
    main()
