from __future__ import annotations

"""Evaluate cached Traj-TracIn scores against multiple cached LDS seed targets.

The expensive target values live in per-seed lds_results.csv files generated by
standard LDS eval. This runner reuses those true_f values and recomputes only
the Traj-TracIn subset score sums for projected stream scores and/or full-dim
term score artifacts.
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path


PROMPTED_QUERIES = ("horse", "automobile", "horse_automobile")


def parse_ints(text: str) -> list[int]:
    return [int(part) for part in text.replace(",", " ").split() if part.strip()]


def parse_strings(text: str) -> list[str]:
    return [part.strip() for part in text.replace(",", " ").split() if part.strip()]


def query_path_tag(query: str) -> str:
    return query.replace(",", "_").replace("__", "_")


def query_filter(mode: str, query: str, initial_seed: int) -> str:
    if mode == "unprompted":
        return f"unprompted/initial_seed_{initial_seed}/shared_query/proj_4096/query_gradient_artifact.npz"
    return f"query_{query_path_tag(query)}/initial_seed_{initial_seed}/shared_query/proj_4096/query_gradient_artifact.npz"


def eval_base(result_root: Path, mode: str, query: str, initial_seed: int) -> Path:
    if mode == "unprompted":
        return result_root / "eval" / "unprompted_solo" / "unprompted" / f"initial_seed_{initial_seed}"
    return result_root / "eval" / "prompted_solo" / f"query_{query_path_tag(query)}" / f"initial_seed_{initial_seed}"


def find_target_csv(
    result_root: Path,
    *,
    mode: str,
    query: str,
    initial_seed: int,
    target_function: str,
    pred_tag: str,
    lds_m: int,
    lds_pct: int,
    lds_seed: int,
) -> Path:
    root = eval_base(result_root, mode, query, initial_seed)
    suffix = f"m_{lds_m}_k_"
    seed_tag = f"_pct_{lds_pct}_subset_seed_{lds_seed}"
    matches = []
    for csv_path in root.rglob("lds_results.csv"):
        parts = csv_path.parts
        if target_function not in parts or pred_tag not in parts:
            continue
        model_name = csv_path.parent.name
        if model_name.startswith(suffix) and model_name.endswith(seed_tag):
            matches.append(csv_path)
    if not matches:
        raise FileNotFoundError(
            f"No cached LDS target for mode={mode} query={query} initial_seed={initial_seed} "
            f"target={target_function} lds_seed={lds_seed} under {root}"
        )
    # Any algorithm's lds_results.csv has the same true_f; prefer DAS caches when available.
    matches = sorted(matches, key=lambda p: (0 if "/lds/das_" in str(p) or "/lds/das" in str(p) else 1, str(p)))
    return matches[0]


def projected_stream_npz(result_root: Path, mode: str, train_seed: int) -> Path:
    mode_dir = "unprompted_solo" if mode == "unprompted" else "prompted_solo"
    return (
        result_root
        / "projected_traj_tracin_artifacts"
        / mode_dir
        / f"train_seed_{train_seed}"
        / "stream_scores"
        / "cache_4096"
        / "proj_256_512_1024_2048_4096"
        / "stream_scores_merged.npz"
    )

def full_term_artifacts(result_root: Path, *, mode: str, query: str, initial_seed: int, train_seed: int) -> list[Path]:
    if mode == "unprompted":
        root = (
            result_root
            / "attribution_score"
            / "unprompted_solo"
            / f"train_seed_{train_seed}"
            / "unprompted"
            / f"initial_seed_{initial_seed}"
        )
        pattern = "traj_tracin_unprompted_range_*/full_dim_term_scores.npz"
    else:
        root = (
            result_root
            / "attribution_score"
            / "prompted_solo"
            / f"train_seed_{train_seed}"
            / f"query_{query_path_tag(query)}"
            / f"initial_seed_{initial_seed}"
        )
        pattern = "traj_tracin_range_*/full_dim_term_scores.npz"
    paths = sorted(root.glob(pattern))
    if not paths:
        raise FileNotFoundError(f"No full_dim_term_scores.npz artifacts under {root}")
    return paths


def run(cmd: list[str], *, dry_run: bool) -> None:
    print("+ " + " ".join(cmd), flush=True)
    if not dry_run:
        subprocess.check_call(cmd)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", default=".", help="Repository root. Defaults to current directory.")
    parser.add_argument("--experiment-tag", default=os.environ.get("EXPERIMENT_TAG", "experiment1_67"))
    parser.add_argument("--train-seed", type=int, default=int(os.environ.get("TRAIN_SEED", "67")))
    parser.add_argument("--initial-seed", type=int, default=int(os.environ.get("INITIAL_SEED", "7")))
    parser.add_argument("--lds-seeds", default="0-15", help="Space/comma list, or A-B range.")
    parser.add_argument("--lds-m", type=int, default=64)
    parser.add_argument("--lds-k", type=int, default=2500)
    parser.add_argument("--lds-pct", type=int, default=25)
    parser.add_argument("--target-function", default="trajectory_state_mse")
    parser.add_argument("--pred-tag", default="pred_kept_sign_m1")
    parser.add_argument("--projection-dims", default="256,512,1024,2048,4096")
    parser.add_argument("--queries", default="horse,automobile,horse_automobile")
    parser.add_argument("--no-unprompted", action="store_true")
    parser.add_argument(
        "--variants",
        default="raw,query_l2_normalized,train_l2_normalized,query_train_l2_normalized",
    )
    parser.add_argument("--only", choices=["both", "projected", "full"], default="both")
    parser.add_argument("--skip-missing", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    if "-" in args.lds_seeds and not any(ch.isspace() for ch in args.lds_seeds) and "," not in args.lds_seeds:
        start, end = [int(part) for part in args.lds_seeds.split("-", 1)]
        lds_seeds = list(range(start, end + 1))
    else:
        lds_seeds = parse_ints(args.lds_seeds)

    repo = Path(args.repo_root).expanduser().resolve()
    result_root = repo / "diffusion_jax_refined" / "cifar2" / "result" / args.experiment_tag
    config = repo / "diffusion_jax_refined" / "cifar2" / "dataset_config.py"
    projected_eval = repo / "diffusion_jax_refined" / "common" / "fast_lds_stream_score_eval.py"
    full_eval = repo / "diffusion_jax_refined" / "common" / "full_dim_term_weighted_lds_eval.py"

    prompted_queries = parse_strings(args.queries)
    specs = [("prompted", query) for query in prompted_queries]
    if not args.no_unprompted:
        specs.append(("unprompted", "unprompted"))
    for mode, query in specs:
        for lds_seed in lds_seeds:
            try:
                target_csv = find_target_csv(
                    result_root,
                    mode=mode,
                    query=query,
                    initial_seed=args.initial_seed,
                    target_function=args.target_function,
                    pred_tag=args.pred_tag,
                    lds_m=args.lds_m,
                    lds_pct=args.lds_pct,
                    lds_seed=lds_seed,
                )
            except FileNotFoundError as exc:
                if args.skip_missing:
                    print(f"[skip] {exc}", flush=True)
                    continue
                raise
            mode_dir = "unprompted" if mode == "unprompted" else "prompted"
            query_dir = "unprompted" if mode == "unprompted" else query_path_tag(query)

            if args.only in ("both", "projected"):
                stream_npz = projected_stream_npz(result_root, mode, args.train_seed)
                if not stream_npz.is_file():
                    if args.skip_missing:
                        print(f"[skip] missing projected stream artifact: {stream_npz}", flush=True)
                        continue
                    raise FileNotFoundError(stream_npz)
                out_dir = (
                    result_root
                    / "eval"
                    / f"projected_stream_cached_lds{args.lds_pct}_seed{args.initial_seed}"
                    / mode_dir
                    / query_dir
                    / args.target_function
                    / f"lds_seed_{lds_seed}"
                )
                run(
                    [
                        sys.executable,
                        str(projected_eval),
                        str(config),
                        "--stream-score-npz",
                        str(stream_npz),
                        "--target-results",
                        str(target_csv),
                        "--query-filter",
                        query_filter(mode, query, args.initial_seed),
                        "--projection-dims",
                        args.projection_dims,
                        "--variants",
                        args.variants,
                        "--mode",
                        mode,
                        "--target-function",
                        args.target_function,
                        "--out-dir",
                        str(out_dir),
                    ],
                    dry_run=args.dry_run,
                )

            if args.only in ("both", "full"):
                try:
                    term_paths = full_term_artifacts(
                        result_root,
                        mode=mode,
                        query=query,
                        initial_seed=args.initial_seed,
                        train_seed=args.train_seed,
                    )
                except FileNotFoundError as exc:
                    if args.skip_missing:
                        print(f"[skip] {exc}", flush=True)
                        continue
                    raise
                out_dir = (
                    result_root
                    / "eval"
                    / f"full_dim_cached_lds{args.lds_pct}_seed{args.initial_seed}"
                    / mode_dir
                    / query_dir
                    / args.target_function
                    / f"lds_seed_{lds_seed}"
                    / "raw"
                )
                run(
                    [
                        sys.executable,
                        str(full_eval),
                        "--term-score-npz",
                        ",".join(str(path) for path in term_paths),
                        "--target-results",
                        str(target_csv),
                        "--mode",
                        mode,
                        "--query",
                        query,
                        "--target-function",
                        args.target_function,
                        "--out-dir",
                        str(out_dir),
                    ],
                    dry_run=args.dry_run,
                )


if __name__ == "__main__":
    main()
